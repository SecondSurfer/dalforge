// Main validation function that calls smaller validators.
func ValidateEntityConfig(entity EntityConfig) error {
	var errs []string

	// Validate entity name.
	errs = append(errs, validateEntityName(entity.Name)...)

	// Validate version.
	errs = append(errs, validateVersion(entity.Version)...)

	// Validate columns.
	errs = append(errs, validateColumns(entity.Columns)...)

	// Validate operations.
	errs = append(errs, validateOperationConfig(entity.Operations, entity.Columns, entity.Name)...)

	// Validate caching config.
	errs = append(errs, validateCachingConfig(entity.Caching)...)

	// Validate circuitbreaker config.
	errs = append(errs, validateCircuitBreakerConfig(entity.CircuitBreaker)...)

	errs = append(errs, validateBufferedCounters(entity.BufferedCounters, entity.Operations.UpsertsBulk, entity.Columns, entity.Caching)...)

	if len(errs) > 0 {
		return errors.New(strings.Join(errs, "\n"))
	}
	return nil
}

// validateEntityName verifies the entity name is longer than 3 characters,
// has no spaces and is snake_cased.
func validateEntityName(name string) []string {
	var errs []string
	if len(name) < 3 {
		errs = append(errs, "entity name must be at least 3 characters")
	}
	if strings.Contains(name, " ") {
		errs = append(errs, "entity name must not contain spaces")
	}
	if !isSnakeCase(name) {
		errs = append(errs, "entity name must be in snake_case")
	}
	return errs
}

// validateVersion ensures version is not empty and follows a pattern like "v1", "v2", etc.
func validateVersion(version string) []string {
	var errs []string
	if strings.TrimSpace(version) == "" {
		errs = append(errs, "version cannot be empty")
	} else {
		if match, _ := regexp.MatchString(`^v\d+$`, version); !match {
			errs = append(errs, "version should be in the format v<number>, e.g., v1, v2")
		}
	}
	return errs
}

// validateColumns checks that each column name is snake_cased, has no spaces,
// and the type is supported.
func validateColumns(columns map[string]Column) []string {
	var errs []string
	allowedTypes := map[string]bool{
		"int8":     true,
		"int16":    true,
		"int32":    true,
		"int64":    true,
		"float":    true,
		"varchar":  true,
		"text":     true,
		"bool":     true,
		"date":     true,
		"time":     true,
		"datetime": true,
		"uid":      true,
		"json":     true,
	}

	for colName, col := range columns {
		if strings.Contains(colName, " ") {
			errs = append(errs, fmt.Sprintf("column name '%s' must not contain spaces", colName))
		}
		if !isSnakeCase(colName) {
			errs = append(errs, fmt.Sprintf("column name '%s' must be in snake_case", colName))
		}
		if !allowedTypes[col.Type] {
			errs = append(errs, fmt.Sprintf("column '%s' has unsupported type '%s'", colName, col.Type))
		}

		// New validation rule for uid prefixes
		if col.Type == "uid" && col.Unique {
			if strings.TrimSpace(col.Prefix) == "" {
				errs = append(errs, fmt.Sprintf("column '%s' of type 'uid' requires a non-empty 'prefix'", colName))
			} else if !isSnakeCase(col.Prefix) {
				errs = append(errs, fmt.Sprintf("prefix '%s' for column '%s' must be in snake_case", col.Prefix, colName))
			}
		}
	}
	return errs
}

// validateOperationConfig validates Gets and Lists in operations.
// For Gets: each referenced column must exist and be marked as unique.
// For Lists: it calls validateListConfigs.
// validateOperationConfig validates Gets, Lists, and Deletes in operations.
func validateOperationConfig(ops OperationConfig, columns map[string]Column, entityName string) []string {
	var errs []string

	// 🚀 NEW: Global name collision tracker
	seenNames := make(map[string]string)

	checkName := func(name, opType string) {
		if name == "" {
			return // Let the specific validators handle empty/short names
		}

		// To ensure we don't have casing collisions in Go (e.g., "list_by_id" vs "ListById"),
		// we track the standardized PascalCase Go function name that will be generated.
		goFuncName := PascalCaser(name)

		if existingOpType, exists := seenNames[goFuncName]; exists {
			errs = append(errs, fmt.Sprintf("duplicate operation name '%s' found in '%s' (would collide with '%s' generated by '%s')", name, opType, goFuncName, existingOpType))
		} else {
			seenNames[goFuncName] = opType
		}
	}

	// Check all explicitly named operations for collisions
	for _, l := range ops.Lists {
		checkName(l.Name, "lists")
	}
	for _, lb := range ops.ListsBulk {
		checkName(lb.Name, "listsBulk")
	}
	for _, u := range ops.UpdatesBulk {
		checkName(u.Name, "updatesBulk")
	}
	for _, d := range ops.Deletes {
		checkName(d.Name, "deletes")
	}
	for _, p := range ops.Plucks {
		checkName(p.Name, "plucks")
	}
	for _, u := range ops.UpsertsBulk {
		checkName(u.Name, "upsertsBulk")
	}

	// ARCHITECTURAL GUARDRAIL: If an entity has paginated lists, it MUST have a bulk ID fetcher.
	// This ensures the list cache can seamlessly resolve missing individual items (scatter-gather)
	// when items are evicted from the local memory cache due to capacity limits.
	if len(ops.Lists) > 0 {
		hasBulkID := false
		for _, col := range ops.GetsBulk {
			if col == "id" {
				hasBulkID = true
				break
			}
		}
		if !hasBulkID {
			errs = append(errs, fmt.Sprintf("entity '%s' defines 'lists', which requires 'id' to be declared in 'getsBulk' to support scatter-gather cache resolution", entityName))
		}
	}

	// Validate Gets.
	for _, colName := range ops.Gets {
		col, exists := columns[colName]
		if !exists {
			errs = append(errs, fmt.Sprintf("get operation refers to unknown column '%s'", colName))
		} else if !col.Unique {
			errs = append(errs, fmt.Sprintf("get operation requires column '%s' to be unique", colName))
		}
	}

	// Validate GetsBulk (NEW)
	errs = append(errs, validateGetsBulk(ops.GetsBulk, columns)...)

	// Validate Lists.
	errs = append(errs, validateListConfigs(ops.Lists, columns)...)

	// Validate Deletes.
	errs = append(errs, validateDeleteConfigs(ops.Deletes, columns)...)

	// Validate UpdatesBulk (NEW)
	errs = append(errs, validateUpdatesBulk(ops.UpdatesBulk, columns)...)

	// Validate ListsBulk (NEW)
	errs = append(errs, validateListsBulk(ops.ListsBulk, columns)...)

	errs = append(errs, validatePlucks(ops.Plucks, columns)...)

	errs = append(errs, validateUpsertsBulk(ops.UpsertsBulk, columns)...)

	return errs
}

func validatePlucks(plucks []PluckConfig, columns map[string]Column) []string {
	var errs []string
	allowedDefaults := map[string]bool{"created": true, "id": true, "updated": true}

	for _, pluck := range plucks {
		if len(pluck.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("pluck name '%s' must be longer than 4 characters", pluck.Name))
		}
		if !isSnakeCase(pluck.Name) {
			errs = append(errs, fmt.Sprintf("pluck name '%s' must be in snake_case", pluck.Name))
		}

		// Validate target column exists
		if _, exists := columns[pluck.Column]; !exists && !allowedDefaults[pluck.Column] {
			errs = append(errs, fmt.Sprintf("pluck '%s' refers to unknown column '%s'", pluck.Name, pluck.Column))
		}

		// Validate TypeMapping targets exist
		for paramName, mappedCol := range pluck.TypeMapping {
			if _, exists := columns[mappedCol]; !exists && !allowedDefaults[mappedCol] {
				errs = append(errs, fmt.Sprintf("typeMapping column '%s' for param '%s' in pluck '%s' is not defined", mappedCol, paramName, pluck.Name))
			}
		}
	}
	return errs
}

// 2. Add the new validation function at the bottom of the file:
func validateListsBulk(lists []ListBulkConfig, columns map[string]Column) []string {
	var errs []string

	// Define the allowed default columns for this scope
	allowedDefaults := map[string]bool{"created": true, "id": true, "updated": true}

	for _, list := range lists {
		// Validate Name
		if len(list.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("listsBulk name '%s' must be longer than 4 characters", list.Name))
		}
		if strings.Contains(list.Name, " ") {
			errs = append(errs, fmt.Sprintf("listsBulk name '%s' must not contain spaces", list.Name))
		}
		if !isSnakeCase(list.Name) {
			errs = append(errs, fmt.Sprintf("listsBulk name '%s' must be in snake_case", list.Name))
		}

		// 🚀 NEW: Validate WhereIn for Unique constraints
		if list.WhereIn != "" {
			if list.WhereIn == "id" {
				errs = append(errs, fmt.Sprintf("listsBulk '%s' uses whereIn on 'id' which is unique. Use 'getsBulk' instead.", list.Name))
			} else if col, exists := columns[list.WhereIn]; exists {
				if col.Unique {
					errs = append(errs, fmt.Sprintf("listsBulk '%s' uses whereIn on a unique column '%s'. Use 'getsBulk' instead for optimal caching.", list.Name, list.WhereIn))
				}
			} else {
				errs = append(errs, fmt.Sprintf("listsBulk '%s' refers to unknown whereIn column '%s'", list.Name, list.WhereIn))
			}
		}

		// NEW: Validate TypeMapping targets exist for standard 'Where' clause
		for paramName, mappedCol := range list.TypeMapping {
			if _, exists := columns[mappedCol]; !exists && !allowedDefaults[mappedCol] {
				errs = append(errs, fmt.Sprintf("typeMapping column '%s' for param '%s' in listsBulk '%s' is not defined", mappedCol, paramName, list.Name))
			}
		}
	}
	return errs
}

// validateGetsBulk ensures that columns used for bulk gets exist and are unique.
func validateGetsBulk(getsBulk []string, columns map[string]Column) []string {
	var errs []string
	for _, colName := range getsBulk {
		if colName == "id" {
			continue // ID is perfectly fine to use for bulk gets
		}
		col, exists := columns[colName]
		if !exists {
			errs = append(errs, fmt.Sprintf("getsBulk operation refers to unknown column '%s'", colName))
		} else if !col.Unique {
			errs = append(errs, fmt.Sprintf("getsBulk operation requires column '%s' to be unique", colName))
		}
	}
	return errs
}

// validateUpdatesBulk ensures bulk updates are configured correctly safely.
func validateUpdatesBulk(updates []UpdateBulkConfig, columns map[string]Column) []string {
	var errs []string

	for _, upd := range updates {
		// 1. Validate Name
		if len(upd.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("updatesBulk name '%s' must be longer than 4 characters", upd.Name))
		}
		if strings.Contains(upd.Name, " ") {
			errs = append(errs, fmt.Sprintf("updatesBulk name '%s' must not contain spaces", upd.Name))
		}
		if !isSnakeCase(upd.Name) {
			errs = append(errs, fmt.Sprintf("updatesBulk name '%s' must be in snake_case", upd.Name))
		}

		// 2. Validate WhereIn column
		if upd.WhereIn != "id" {
			if _, exists := columns[upd.WhereIn]; !exists {
				errs = append(errs, fmt.Sprintf("updatesBulk '%s' refers to unknown whereIn column '%s'", upd.Name, upd.WhereIn))
			}
		}

		// 3. Validate Set columns
		if len(upd.Set) == 0 {
			errs = append(errs, fmt.Sprintf("updatesBulk '%s' must specify at least one column in 'set'", upd.Name))
		}
		for _, setCol := range upd.Set {
			if setCol == "id" || setCol == "created" || setCol == "updated" {
				errs = append(errs, fmt.Sprintf("updatesBulk '%s' cannot update reserved column '%s'", upd.Name, setCol))
			} else if _, exists := columns[setCol]; !exists {
				errs = append(errs, fmt.Sprintf("updatesBulk '%s' refers to unknown set column '%s'", upd.Name, setCol))
			}
		}
	}
	return errs
}

