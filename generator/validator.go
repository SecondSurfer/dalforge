// validateListConfigs validates each list config:
//   - List name must be longer than 4 characters, snake_cased, and have no spaces.
//   - Order: if provided, must contain exactly one column that exists in the columns map
//     or is one of the allowed defaults: "created", "id", or "updated".
func validateListConfigs(lists []ListConfig, columns map[string]Column) []string {
	var errs []string
	allowedDefaults := map[string]bool{"created": true, "id": true, "updated": true}

	for _, list := range lists {
		if len(list.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("list name '%s' must be longer than 4 characters", list.Name))
		}
		if strings.Contains(list.Name, " ") {
			errs = append(errs, fmt.Sprintf("list name '%s' must not contain spaces", list.Name))
		}
		if !isSnakeCase(list.Name) {
			errs = append(errs, fmt.Sprintf("list name '%s' must be in snake_case. eg. list_by_age, most_recent", list.Name))
		}

		order := strings.TrimSpace(list.Order)
		if order != "" {
			parts := strings.Split(order, ",")
			if len(parts) != 1 {
				errs = append(errs, fmt.Sprintf("list '%s' order must contain exactly one column", list.Name))
			} else {
				orderCol := strings.TrimSpace(parts[0])
				if strings.Contains(orderCol, " ") {
					errs = append(errs, fmt.Sprintf("order column '%s' in list '%s' must not contain spaces", orderCol, list.Name))
				}
				if _, exists := columns[orderCol]; !exists && !allowedDefaults[orderCol] {
					errs = append(errs, fmt.Sprintf("order column '%s' in list '%s' is not defined and not a default column", orderCol, list.Name))
				}
			}
		}

		// Validate TypeMapping targets exist
		for paramName, mappedCol := range list.TypeMapping {
			if _, exists := columns[mappedCol]; !exists && !allowedDefaults[mappedCol] {
				errs = append(errs, fmt.Sprintf("typeMapping column '%s' for param '%s' in list '%s' is not defined", mappedCol, paramName, list.Name))
			}
		}
	}
	return errs
}

// validateCachingConfig validates caching configuration.
func validateCachingConfig(c CachingConfig) []string {
	var errs []string

	// 🚀 NEW: Enforce 'memory' and reject 'redis' explicitly
	lowerType := strings.ToLower(c.Type)
	if lowerType == "redis" {
		errs = append(errs, "caching type 'redis' is not implemented yet")
	} else if lowerType != "memory" {
		errs = append(errs, fmt.Sprintf("caching type must be 'memory', got '%s'", c.Type))
	}

	if c.SingleExpirationSeconds <= 1 {
		errs = append(errs, "singleExpirationSeconds must be greater than 1")
	}
	if c.ListExpirationSeconds <= 1 {
		errs = append(errs, "listExpirationSeconds must be greater than 1")
	}
	if c.MaxItemsCount <= 10 {
		errs = append(errs, "maxItemsCount must be greater than 10")
	}

	if c.ListInvalidation == "expire" && c.ListExpirationSeconds > 60 {
		errs = append(errs, fmt.Sprintf("when listInvalidation is 'expire', listExpirationSeconds must be 60 or less to prevent severe data staleness. Got: %d", c.ListExpirationSeconds))
	}

	if c.ListInvalidation != "flush" && c.ListInvalidation != "expire" && c.ListInvalidation != "epoch" {
		errs = append(errs, fmt.Sprintf("listInvalidation must be 'flush', 'expire', or 'epoch', got '%s'", c.ListInvalidation))
	}

	// Update the staleness guardrail
	if (c.ListInvalidation == "expire" || c.ListInvalidation == "epoch") && c.ListExpirationSeconds > 60 {
		errs = append(errs, fmt.Sprintf("when listInvalidation is '%s', listExpirationSeconds must be 60 or less to prevent memory bloat. Got: %d", c.ListInvalidation, c.ListExpirationSeconds))
	}

	return errs
}

func validateCircuitBreakerConfig(c CircuitBreakerConfig) []string {
	var errs []string
	if c.ConsecutiveFailures < 1 {
		errs = append(errs, fmt.Sprintf("consecutiveFailures should be 1 or more. got '%v'", c.ConsecutiveFailures))
	}
	if c.TimeoutSeconds < 1 {
		errs = append(errs, fmt.Sprintf("timeoutSeconds should be 1 or more. got '%v'", c.TimeoutSeconds))
	}
	return errs
}

// isSnakeCase checks if a string is in snake_case: only lowercase letters, numbers, and underscores.
func isSnakeCase(s string) bool {
	re := regexp.MustCompile(`^[a-z0-9]+(_[a-z0-9]+)*$`)
	return re.MatchString(s)
}

// validateUpsertsBulk ensures bulk upserts are configured correctly safely.
func validateUpsertsBulk(upserts []UpsertBulkConfig, columns map[string]Column) []string {
	var errs []string

	for _, u := range upserts {
		// 1. Validate Name
		if len(u.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("upsertsBulk name '%s' must be longer than 4 characters", u.Name))
		}
		if strings.Contains(u.Name, " ") {
			errs = append(errs, fmt.Sprintf("upsertsBulk name '%s' must not contain spaces", u.Name))
		}
		if !isSnakeCase(u.Name) {
			errs = append(errs, fmt.Sprintf("upsertsBulk name '%s' must be in snake_case", u.Name))
		}

		// 2. Validate ConflictTarget column
		if u.ConflictTarget != "id" {
			if col, exists := columns[u.ConflictTarget]; !exists {
				errs = append(errs, fmt.Sprintf("upsertsBulk '%s' refers to unknown conflictTarget column '%s'", u.Name, u.ConflictTarget))
			} else if !col.Unique {
				errs = append(errs, fmt.Sprintf("upsertsBulk '%s' conflictTarget '%s' must be a unique column for MySQL UPSERT to work reliably", u.Name, u.ConflictTarget))
			}
		}

		// 3. Validate UpdateColumns
		if len(u.UpdateColumns) == 0 {
			errs = append(errs, fmt.Sprintf("upsertsBulk '%s' must specify at least one column in 'updateColumns'", u.Name))
		}
		for _, updCol := range u.UpdateColumns {
			if updCol == "id" || updCol == "created" {
				errs = append(errs, fmt.Sprintf("upsertsBulk '%s' cannot update immutable column '%s'", u.Name, updCol))
			} else if updCol != "updated" {
				if _, exists := columns[updCol]; !exists {
					errs = append(errs, fmt.Sprintf("upsertsBulk '%s' refers to unknown update column '%s'", u.Name, updCol))
				}
			}
		}
	}
	return errs
}

func validateBufferedCounters(counters []BufferedCounterConfig, upserts []UpsertBulkConfig, columns map[string]Column, caching CachingConfig) []string {
	var errs []string

	for _, bc := range counters {
		if len(bc.Name) <= 4 {
			errs = append(errs, fmt.Sprintf("bufferedCounter name '%s' must be longer than 4 characters", bc.Name))
		}
		if !isSnakeCase(bc.Name) {
			errs = append(errs, fmt.Sprintf("bufferedCounter name '%s' must be in snake_case", bc.Name))
		}

		if col, exists := columns[bc.Column]; !exists {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' refers to unknown column '%s'", bc.Name, bc.Column))
		} else if col.Type != "int32" && col.Type != "int64" && col.Type != "int8" {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' column '%s' must be a numeric type (int8/int32/int64) for atomic increments", bc.Name, bc.Column))
		}

		if _, exists := columns[bc.GroupBy]; !exists && bc.GroupBy != "id" {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' refers to unknown groupBy column '%s'", bc.Name, bc.GroupBy))
		}

		if bc.FlushIntervalSeconds < 10 {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' flushIntervalSeconds must be at least 10 seconds to prevent Redis CPU spikes", bc.Name))
		}

		// Architectural guardrail: Buffers update MySQL outside of standard CRUD flows.
		// Global list caches would become stale if not set to 'expire' or 'none'.
		if caching.ListInvalidation == "flush" || caching.ListInvalidation == "epoch" {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' requires entity listInvalidation to be 'expire' or 'none', currently '%s'. Asynchronous background flushes cannot safely invalidate global epochs without causing cache stampedes.", bc.Name, caching.ListInvalidation))
		}

		// 🚀 NEW: Ensure a matching upsertsBulk operation exists to actually persist the buffer
		hasMatchingUpsert := false
		for _, u := range upserts {
			if u.Increment {
				for _, updCol := range u.UpdateColumns {
					if updCol == bc.Column {
						hasMatchingUpsert = true
						break
					}
				}
			}
			if hasMatchingUpsert {
				break
			}
		}

		if !hasMatchingUpsert {
			errs = append(errs, fmt.Sprintf("bufferedCounter '%s' targeting column '%s' requires a corresponding 'upsertsBulk' operation with 'increment: true' and '%s' in 'updateColumns'", bc.Name, bc.Column, bc.Column))
		}
	}

	return errs
}
